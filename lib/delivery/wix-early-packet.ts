const sha256 = (value: string) => createHash("sha256").update(value).digest("hex");

/**
 * Wix Custom Code rejects an entry at 15,000 characters. The Atelier startup
 * build chunks at 14,000 and so do we, leaving room for the wrapper script.
 */
export const PACKET_CHUNK_CHARACTERS = 14_000;
export const PACKET_MAX_CHARACTERS = 15_000;

export class WixEarlyPacketError extends Error {
  constructor(message: string, readonly status = 400) {
    super(message);
    this.name = "WixEarlyPacketError";
  }
}

export type EarlyPacket = {
  index: number;
  count: number;
  name: string;
  html: string;
  characters: number;
};

export type WixPageComponentResult = {
  tag: string;
  route: string;
  url: string;
  sourcePath: string | null;
  sourceSha256: string;
  packets: Array<{ id: string; name: string; index: number; characters: number; created: boolean; readback: "match" | "mismatch" }>;
  placement: "found" | "missing" | "unavailable";
};

function routePath(route: string): string {
  const trimmed = route.trim();
  if (!trimmed.startsWith("/") || trimmed === "/" || /[?#\s]/.test(trimmed) || trimmed.includes("//") || trimmed.split("/").includes("..")) {
    throw new WixEarlyPacketError("A page route must be one exact non-root path, such as /abat-jour-sur-mesure", 400);
  }
  return trimmed.replace(/\/+$/, "");
}

function siteUrl(domain: string, route: string): string {
  const host = domain.trim().replace(/^https?:\/\//i, "").replace(/\/+$/, "");
  return `https://${host}${route}`;
}

function slugFor(route: string): string {
  return route.replace(/^\/+/, "").replace(/\/+/g, "-").replace(/[^a-z0-9-]/gi, "-").replace(/-+/g, "-").replace(/^-|-$/g, "").toLowerCase();
}

/**
 * The tag a page component is registered under. The site's own components
 * share a prefix (`atelier-`), so a new page keeps that prefix and adds the
 * route slug. A site without a shared prefix gets a neutral one.
 */
export function pageComponentTag(route: string, existingTags: string[]): string {
  const slug = slugFor(route);
  if (!slug) throw new WixEarlyPacketError("The route has no usable slug for a component tag", 400);
  const prefixes = existingTags
    .map((tag) => tag.match(/^([a-z][a-z0-9]*-)/)?.[1] ?? "")
    .filter(Boolean);
  const shared = prefixes.length
    ? prefixes.reduce((common, prefix) => {
        let next = "";
        for (let index = 0; index < Math.min(common.length, prefix.length); index += 1) {
          if (common[index] !== prefix[index]) break;
          next += common[index];
        }
        return next;
      })
    : "";
  const prefix = shared.length >= 3 ? shared : "crawlseo-";
  return `${prefix}${slug}-v1`;
}

/**
 * Wrap the reviewed fragment in a custom element.
 *
 * The fragment already scopes every selector with its task marker, so the
 * element renders into the light DOM: the copy stays in the document for
 * crawlers instead of hiding inside a shadow root. JSON-LD is moved to the
 * document head because structured data inside a custom element is not read.
 */
export function buildPageComponentSource(input: { tag: string; html: string; taskId: string }): string {
  if (!/^[a-z][a-z0-9]*-[a-z0-9-]*$/.test(input.tag)) {
    throw new WixEarlyPacketError(`"${input.tag}" is not a valid custom element tag`, 400);
  }
  if (!input.html.trim()) throw new WixEarlyPacketError("The page HTML is empty", 400);
  return `// Generated by CrawlSEO for task ${input.taskId}. Edit the page in CrawlSEO, not here.
(() => {
  const TAG = ${JSON.stringify(input.tag)};
  const TASK = ${JSON.stringify(input.taskId)};
  if (customElements.get(TAG)) return;
  const HTML = ${JSON.stringify(input.html)};
  class CrawlSeoPage extends HTMLElement {
    connectedCallback() {
      if (this.dataset.crawlseoRendered === "1") return;
      this.dataset.crawlseoRendered = "1";
      this.innerHTML = HTML;
      // Structured data must live in the document head, not inside the element.
      for (const node of this.querySelectorAll('script[type="application/ld+json"]')) {
        const copy = document.createElement("script");
        copy.type = "application/ld+json";
        copy.textContent = node.textContent;
        copy.dataset.crawlseoTask = TASK;
        document.head.append(copy);
        node.remove();
      }
    }
  }
  customElements.define(TAG, CrawlSeoPage);
})();
`;
}

/**
 * Build the early-registration packets for one component.
 *
 * Each packet is a HEAD script that only runs on its own route, honours the
 * site's `?earlyElements=off` control, and defines the element before Wix's
 * own custom-element loader runs. A long source is split into ordered chunks
 * that concatenate into one base64 payload; the last chunk decompresses it.
 */
export function buildEarlyPackets(input: {
  tag: string;
  route: string;
  source: string;
  chunkCharacters?: number;
}): EarlyPacket[] {
  const route = routePath(input.route);
  const chunkCharacters = input.chunkCharacters ?? PACKET_CHUNK_CHARACTERS;
  const encoded = gzipSync(Buffer.from(input.source, "utf8"), { level: 9 }).toString("base64");
  const chunks: string[] = [];
  for (let index = 0; index < encoded.length; index += chunkCharacters) {
    chunks.push(encoded.slice(index, index + chunkCharacters));
  }
  const count = chunks.length;
  const key = sha256(input.source).slice(0, 16);
  const guard = `const p=location.pathname.replace(/\\/+$/,"")||"/",r=${JSON.stringify(route)},q=p.replace(/^\\/[a-z]{2}(?=\\/)/,"");if(p!==r&&q!==r)return;if(new URLSearchParams(location.search).get("earlyElements")==="off")return;`;
  return chunks.map((chunk, index) => {
    const store = `(window.__crawlseoEarly||(window.__crawlseoEarly={}))[${JSON.stringify(key)}]=(window.__crawlseoEarly[${JSON.stringify(key)}]||"")+${JSON.stringify(chunk)};`;
    const drain = index === count - 1
      ? `const b=window.__crawlseoEarly[${JSON.stringify(key)}];if(!b)return;const bytes=Uint8Array.from(atob(b),c=>c.charCodeAt(0));new Response(new Blob([bytes]).stream().pipeThrough(new DecompressionStream("gzip"))).text().then(source=>{if(customElements.get(${JSON.stringify(input.tag)}))return;const script=document.createElement("script");script.textContent=source;document.head.append(script)}).catch(()=>{});`
      : "";
    const html = `<script>(()=>{${guard}${store}${drain}})();</script>`;
    if (html.length >= PACKET_MAX_CHARACTERS) {
      throw new WixEarlyPacketError(`Packet ${index + 1} is ${html.length} characters; Wix rejects entries at ${PACKET_MAX_CHARACTERS}`, 500);
    }
    return {
      index,
      count,
      name: `CrawlSEO early packet — ${input.tag} — ${index + 1}`,
      html,
      characters: html.length,
    };
  });
}

async function existingComponentTags(repoPath: string | null): Promise<string[]> {
  if (!repoPath) return [];
  const directory = path.join(repoPath, "src", "public", "custom-elements");
  const entries = await readdir(directory).catch(() => []);
  return entries
    .filter((entry) => entry.endsWith(".js"))
    .map((entry) => entry.slice(0, -3))
    .filter((tag) => /^[a-z][a-z0-9]*-[a-z0-9-]*$/.test(tag));
}

async function writeComponentSource(repoPath: string | null, tag: string, source: string): Promise<string | null> {
  if (!repoPath) return null;
  const directory = path.join(repoPath, "src", "public", "custom-elements");
  const exists = await readdir(directory).then(() => true).catch(() => false);
  if (!exists) return null;
  const file = path.join(directory, `${tag}.js`);
  await mkdir(directory, { recursive: true });
  await writeFile(file, source, "utf8");
  return file;
}

type ManagedEmbed = { id: string; name: string; htmlSha256?: string };

async function managedEmbeds(alias: string): Promise<ManagedEmbed[]> {
  const listed = await listBridgeSnippets(alias) as { snippets?: Array<{ id?: string; name?: string; htmlSha256?: string }> };
  return (listed.snippets ?? [])
    .filter((snippet): snippet is ManagedEmbed => typeof snippet.id === "string" && typeof snippet.name === "string")
    .filter((snippet) => snippet.name.startsWith("CrawlSEO early packet — "));
}

async function writePacketFile(packet: EarlyPacket): Promise<string> {
  const directory = path.join(process.cwd(), ".tmp", "wix-packets");
  await mkdir(directory, { recursive: true });
  const file = path.join(directory, `${packet.name.replace(/[^a-z0-9]+/gi, "-").toLowerCase()}.html`);
  await writeFile(file, packet.html, "utf8");
  return file;
}

/**
 * Deliver a reviewed page as an early-registered custom element.
 *
 * The component source is written to the site repository so the site's own
 * startup build can adopt it, and the packets are deployed as HEAD Custom
 * Embeds. Wix exposes the page filter as read-only, so the packet is created
 * site-wide and guards itself by route; a human narrows its page scope in the
 * Wix Custom Code panel to stop the bytes transferring elsewhere.
 */
export async function deliverWixPageComponent(input: {
  siteId: string;
  route: string;
  html: string;
  taskId: string;
}): Promise<WixPageComponentResult> {
  const route = routePath(input.route);
  const site = await db.site.findUnique({
    where: { id: input.siteId },
    select: { id: true, domain: true, retiredAt: true },
  });
  if (!site || site.retiredAt) throw new WixEarlyPacketError("Site not found or retired", 404);
  const config = await getSiteDeliveryConfig(input.siteId);
  if (!config || !config.enabled) throw new WixEarlyPacketError("Wix delivery is not enabled for this site", 409);
  const alias = config.bridgeAlias.trim();
  if (!alias) throw new WixEarlyPacketError("This site has no Wix bridge alias configured", 409);

  await assertNegotiatedWixBridgeOperations(alias, ["read_embed", "write_embed"]);

  const repoPath = config?.repoPath?.trim() || null;
  const tag = pageComponentTag(route, await existingComponentTags(repoPath));
  const source = buildPageComponentSource({ tag, html: input.html, taskId: input.taskId });
  const sourcePath = await writeComponentSource(repoPath, tag, source);
  const packets = buildEarlyPackets({ tag, route, source });

  const existing = await managedEmbeds(alias);
  const results: WixPageComponentResult["packets"] = [];
  for (const packet of packets) {
    const file = await writePacketFile(packet);
    const current = existing.find((embed) => embed.name === packet.name);
    let id: string;
    let created = false;
    if (current) {
      id = current.id;
      await writeBridgeEmbed(alias, id, file, route, true);
    } else {
      const receipt = await createBridgeSnippet(alias, {
        name: packet.name,
        htmlFile: file,
        allPages: true,
        position: "HEAD",
        category: "ESSENTIAL",
        apply: true,
        loadOnce: true,
      }) as { snippetId?: string; id?: string };
      id = String(receipt.snippetId ?? receipt.id ?? "");
      if (!id) throw new WixEarlyPacketError("The bridge did not return the new packet embed id", 502);
      created = true;
    }
    const readback = await readBridgeEmbed(alias, id) as { embed?: { htmlSha256?: string } };
    results.push({
      id,
      name: packet.name,
      index: packet.index,
      characters: packet.characters,
      created,
      readback: readback.embed?.htmlSha256 === sha256(packet.html) ? "match" : "mismatch",
    });
  }

  const url = siteUrl(site.domain, route);
  return {
    tag,
    route,
    url,
    sourcePath,
    sourceSha256: sha256(source),
    packets: results,
    placement: await checkComponentPlacement(url, tag),
  };
}

/**
 * A page is only live once the human places the custom element on it. Wix has
 * no API for adding an element to a page, so the delivery waits for the tag to
 * appear in the rendered document.
 */
export async function checkComponentPlacement(url: string, tag: string, timeoutMs = 30_000): Promise<"found" | "missing" | "unavailable"> {
  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), timeoutMs);
  try {
    const response = await fetch(url, { signal: controller.signal, redirect: "follow" });
    if (!response.ok) return "unavailable";
    const html = await response.text();
    return html.includes(`<${tag}`) ? "found" : "missing";
  } catch {
    return "unavailable";
  } finally {
    clearTimeout(timer);
  }
}

/** Read the component source a delivery wrote, for review or a re-delivery. */
export async function readComponentSource(file: string): Promise<string> {
  return readFile(file, "utf8");
}
